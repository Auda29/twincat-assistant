import {cp,readFile,writeFile,readdir,rm,mkdir} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {createManifest,verifyManifest} from './application-manifest.mjs';
const input=resolve(process.argv[2]),output=resolve(process.argv[3]);
const digest=createHash('sha256').update(await readFile(join(input,'application-manifest.json'))).digest('hex');
if(digest!=='7913a2e74726ba2cc5941bb0e7f918eae121b2ac18e50db79f0b84d08b1b33de')throw new Error('Use the archived real-component baseline');
const original=await verifyManifest(input);
execFileSync('git',['diff','--exit-code','HEAD','--','src'],{stdio:'inherit'});
await mkdir(output);await cp(input,output,{recursive:true});
for(const name of await readdir(join(output,'src')))await rm(join(output,'src',name));
const paths=execFileSync('git',['ls-files','--','src'],{encoding:'utf8'}).trim().split(/\r?\n/);
for(const path of paths)await cp(path,join(output,path));
const integrity=join(output,'src/package-integrity.mjs');
const source=await readFile(integrity,'utf8');if(source.split('const requirePackage = false;').length!==2)throw new Error('Unknown integrity marker');
await writeFile(integrity,source.replace('const requirePackage = false;','const requirePackage = true;'));
await writeFile(join(output,'src/package-runtime.json'),'{"version":1}\n');
await writeFile(join(output,'policy-test-provenance.json'),JSON.stringify({kind:'policy-core-only-regression-on-real-frozen-components',sourceCommit:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),baselineManifestSha256:digest,native85AssemblyAcceptance:false,sourceModules:paths},null,2)+'\n');
await rm(join(output,'application-manifest.json'));
const manifest=await createManifest(output,{version:original.version,architecture:original.architecture});await verifyManifest(output);
console.log(JSON.stringify({sourceCommit:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),files:manifest.files.length,purpose:'Node policy regression; not new native assembly acceptance'}));
